DROP TABLE IF EXISTS partita;
DROP TABLE IF EXISTS arbitro;
DROP TABLE IF EXISTS squadra;
CREATE TABLE squadra (nome VARCHAR(80) PRIMARY KEY, citta VARCHAR(80) NOT NULL, regione VARCHAR(80) NOT NULL);
CREATE TABLE arbitro (codice INTEGER PRIMARY KEY, nome VARCHAR(120) NOT NULL, sezioneAIA VARCHAR(80) NOT NULL, regioneSezioneAIA VARCHAR(80) NOT NULL);
CREATE TABLE partita (stagione INTEGER NOT NULL, 
                      giornata INTEGER NOT NULL CHECK (giornata BETWEEN 1 AND 38), 
                      codice INTEGER NOT NULL CHECK (codice BETWEEN 1 AND 10), 
                      data DATE NOT NULL, 
                      girone VARCHAR(7) NOT NULL CHECK (girone IN ('andata','ritorno')), 
                      squadraCasa VARCHAR(80) NOT NULL REFERENCES squadra(nome), 
                      squadraTrasferta VARCHAR(80) NOT NULL REFERENCES squadra(nome),
                      golCasa INTEGER NOT NULL CHECK (golCasa >= 0), 
                      golTrasferta INTEGER NOT NULL CHECK (golTrasferta >= 0), 
                      arbitro INTEGER REFERENCES arbitro(codice), 
                      PRIMARY KEY (stagione,giornata,codice), 
                      UNIQUE (stagione,squadraCasa,squadraTrasferta), 
                      CHECK (squadraCasa <> squadraTrasferta), 
                      CHECK ((giornata <= 19 AND girone = 'andata') OR (giornata >= 20 AND girone = 'ritorno')));
